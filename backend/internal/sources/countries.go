// CountryName mengubah kode ISO negara menjadi nama
// Indonesianya; kode tak dikenal dikembalikan apa adanya.
func CountryName(code string) string {
	if name, ok := isoCountryNames[strings.ToUpper(strings.TrimSpace(code))]; ok {
		return name
	}
	return code
}
